package com.workaudit.workaudit.controller;

import com.workaudit.workaudit.dto.AuditLogResponse;
import com.workaudit.workaudit.service.AuditLogService;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.*;
import com.workaudit.workaudit.entity.AuditAction;
import org.springframework.data.domain.Page;
import org.springframework.format.annotation.DateTimeFormat;

import java.time.Instant;
import java.util.List;
import java.util.UUID;

@RestController
@RequestMapping("/api/audit-logs")
public class AuditLogController {

    private final AuditLogService auditLogService;

    public AuditLogController(
            AuditLogService auditLogService) {

        this.auditLogService = auditLogService;
    }

    /**
     * Get all audit logs.
     *
     * ADMIN only.
     */
    @GetMapping
    @PreAuthorize("hasRole('ADMIN')")
    public ResponseEntity<List<AuditLogResponse>> getAllLogs() {

        return ResponseEntity.ok(
                auditLogService.getAllLogs()
        );
    }

    /**
     * Get audit logs generated by a specific employee.
     *
     * ADMIN only.
     */
    @GetMapping("/actor/{actorId}")
    @PreAuthorize("hasRole('ADMIN')")
    public ResponseEntity<List<AuditLogResponse>> getLogsByActor(
            @PathVariable UUID actorId) {

        return ResponseEntity.ok(
                auditLogService.getLogsByActor(actorId)
        );
    }

    @GetMapping("/search")
    @PreAuthorize("hasRole('ADMIN')")
    public ResponseEntity<Page<AuditLogResponse>> searchAuditLogs(
            @RequestParam(defaultValue = "0") int page,
            @RequestParam(defaultValue = "20") int size,
            @RequestParam(required = false) AuditAction action,
            @RequestParam(required = false) String entityType,
            @RequestParam(required = false) UUID actorId,
            @RequestParam(required = false)
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE_TIME)
            Instant from,
            @RequestParam(required = false)
            @DateTimeFormat(iso = DateTimeFormat.ISO.DATE_TIME)
            Instant to) {

        return ResponseEntity.ok(
                auditLogService.searchAuditLogs(
                        page,
                        size,
                        action,
                        entityType,
                        actorId,
                        from,
                        to
                )
        );
    }

    /**
     * Get audit logs for a specific entity.
     *
     * Example:
     * /api/audit-logs/entity/EMPLOYEE/{employeeId}
     *
     * ADMIN only.
     */
    @GetMapping("/entity/{entityType}/{entityId}")
    @PreAuthorize("hasRole('ADMIN')")
    public ResponseEntity<List<AuditLogResponse>> getLogsByEntity(
            @PathVariable String entityType,
            @PathVariable UUID entityId) {

        return ResponseEntity.ok(
                auditLogService.getLogsByEntity(
                        entityType,
                        entityId
                )
        );
    }
}